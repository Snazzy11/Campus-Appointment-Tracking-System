#!/usr/bin/env bash
# Bootstrap only: isolated spatial project; no messaging database migration.
set -Eeuo pipefail
umask 077
ROOT="$1"
PROJECT="$2"
cd "$ROOT"
mkdir .deploy-lock || { echo 'Another deployment is active' >&2; exit 1; }
trap 'rmdir "$ROOT/.deploy-lock"' EXIT
cd deploy/spatial-bootstrap
sha256sum -c SHA256SUMS
app() { sudo -n docker compose -p "$PROJECT" --project-directory "$ROOT" --env-file "$ROOT/deploy/ec2.env" -f "$ROOT/compose.yaml" "$@"; }
geo() { sudo -n docker compose -p "${PROJECT}-spatial" --env-file spatial.env -f compose.yaml "$@"; }
if test -f COMPLETE; then echo 'Spatial setup already completed; use normal redeployment.'; exit 0; fi
if ! test -f spatial.env; then
  python3 - "$PROJECT" <<'PY'
import secrets, sys
from pathlib import Path
Path('spatial.env').write_text('SPATIAL_PASSWORD='+secrets.token_hex(32)+'\nREADER_PASSWORD='+secrets.token_hex(32)+'\nAPPLICATION_NETWORK='+sys.argv[1]+'_application\n')
PY
fi
# Files are generated by this script, not arbitrary shell input.
set -a
source spatial.env
set +a
sudo -n docker network inspect "$APPLICATION_NETWORK" >/dev/null
gunzip -c images.tar.gz | sudo -n docker image load
geo up -d --no-build --wait --wait-timeout 120 spatial
export GEO_DATABASE_URL="postgresql+psycopg://spatial:$SPATIAL_PASSWORD@campus-spatial-db:5432/campus_spatial"
operator() { sudo -n docker run --rm --memory 512m --cpus 0.75 --network "$APPLICATION_NETWORK" --env-file operator.env -v "$PWD/campus.osm:/snapshot.osm:ro" campus-spatial-operator:bootstrap "$@"; }
printf 'GEO_DATABASE_URL=%s\n' "$GEO_DATABASE_URL" > operator.env
operator alembic -c geo-alembic.ini upgrade head
COUNT=$(geo exec -T spatial psql -U spatial -d campus_spatial -Atc 'SELECT count(*) FROM geo.features')
if [[ "$COUNT" == 0 ]]; then
  operator python -m scripts.campus_data import --snapshot /snapshot.osm --captured-at "$3"
fi
EDGES=$(geo exec -T spatial psql -U spatial -d campus_spatial -Atc 'SELECT count(*) FROM geo.routing_edges')
if [[ "$EDGES" == 0 ]]; then
  operator python -m scripts.campus_data build-graph --snapshot /snapshot.osm --captured-at "$3"
fi
operator python -m scripts.campus_data validate > quality-report.json
echo "Spatial quality report saved to $PWD/quality-report.json"
geo exec -T spatial psql -v ON_ERROR_STOP=1 -U spatial -d campus_spatial <<SQL
DO \$\$ BEGIN IF NOT EXISTS(SELECT 1 FROM pg_roles WHERE rolname='campus_geo_reader') THEN
CREATE ROLE campus_geo_reader LOGIN PASSWORD '$READER_PASSWORD'; END IF; END \$\$;
GRANT CONNECT ON DATABASE campus_spatial TO campus_geo_reader;
GRANT USAGE ON SCHEMA geo TO campus_geo_reader;
GRANT SELECT ON ALL TABLES IN SCHEMA geo TO campus_geo_reader;
SQL
# Verify both building data and graph before activating the API settings.
geo exec -T spatial psql -v ON_ERROR_STOP=1 -U spatial -d campus_spatial <<'SQL'
DO $$ BEGIN
IF NOT EXISTS(SELECT 1 FROM geo.features WHERE name ILIKE '%pearce%') OR NOT EXISTS(SELECT 1 FROM geo.routing_edges) THEN
RAISE EXCEPTION 'Spatial import incomplete'; END IF; END $$;
SQL
cp "$ROOT/deploy/ec2.env" ec2.env.before-spatial
python3 - "$ROOT/deploy/ec2.env" <<'PY'
import os,sys
from pathlib import Path
p=Path(sys.argv[1]); values={'GEO_DATA_ENABLED':'true','GEO_ROUTING_ENABLED':'true','GEO_DATABASE_URL':'postgresql+psycopg://campus_geo_reader:'+os.environ['READER_PASSWORD']+'@campus-spatial-db:5432/campus_spatial'}
lines=[line for line in p.read_text().splitlines() if line.split('=',1)[0] not in values]
p.write_text('\n'.join(lines+[k+'='+v for k,v in values.items()])+'\n')
PY
rollback() {
  cp ec2.env.before-spatial "$ROOT/deploy/ec2.env"
  app up -d --no-build --no-deps --force-recreate --wait api web || true
  echo 'Spatial activation failed; previous app environment restored.' >&2
}
trap 'rollback' ERR
app up -d --no-build --no-deps --force-recreate --wait --wait-timeout 120 api
app up -d --no-build --no-deps --force-recreate --wait --wait-timeout 60 web
# Use direct API container request; validates actual API credentials and query.
app exec -T api python -c 'import urllib.request; r=urllib.request.urlopen("http://127.0.0.1:8000/api/geo/buildings/search?q=Pearce",timeout=10); assert r.status==200'
trap - ERR
touch COMPLETE
rm -f operator.env
echo 'Production spatial data and routing enabled. Existing messaging database preserved.'
